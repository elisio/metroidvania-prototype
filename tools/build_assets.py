"""Regenerate every game asset from assets/src/reference.jpg.

    python3 tools/build_assets.py            # full build (uses tools/.cache for the slow hero-removal inpaint)
    python3 tools/build_assets.py --clean    # also rebuild the cache
"""
import os
import sys
import json
import shutil
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import numpy as np
from PIL import Image

from common import OUT, TOOLS, ref_rgb, checker, over
import build_bg
import build_tiles
import build_props
import build_hud
import build_hero


def write_manifest():
    entries = {}
    for f in sorted(os.listdir(OUT)):
        if f.endswith(".png"):
            w, h = Image.open(os.path.join(OUT, f)).size
            entries[f[:-4]] = {"file": f, "w": w, "h": h}
    with open(os.path.join(OUT, "manifest.js"), "w") as fh:
        fh.write("// generated by tools/build_assets.py — do not edit by hand\n")
        fh.write("window.ASSET_MANIFEST = " + json.dumps(entries, indent=1) + ";\n")
    return entries


def contact_sheet(entries):
    """All assets on a checkerboard, labelled, max width 1600."""
    import cv2
    W = 1600
    pad = 14
    items = []
    for k, e in entries.items():
        im = np.array(Image.open(os.path.join(OUT, e["file"])).convert("RGBA"))
        s = 1
        if im.shape[1] < 70 and im.shape[0] < 70:
            s = 2
        if im.shape[1] > W - 2 * pad:
            s = (W - 2 * pad) / im.shape[1]
        if s != 1:
            im = cv2.resize(im, (max(1, int(im.shape[1] * s)), max(1, int(im.shape[0] * s))),
                            interpolation=cv2.INTER_NEAREST if s > 1 else cv2.INTER_AREA)
        items.append((k, e, im))
    # shelf packing
    x, y, rowh = pad, pad, 0
    pos = []
    for k, e, im in items:
        h, w = im.shape[:2]
        if x + w + pad > W:
            x = pad
            y += rowh + 22
            rowh = 0
        pos.append((x, y))
        x += w + pad
        rowh = max(rowh, h)
    H = y + rowh + 30
    can = checker(W, H, 8)
    can[..., :3] = (can[..., :3] * 0.8).astype(np.uint8)
    for (k, e, im), (x, y) in zip(items, pos):
        h, w = im.shape[:2]
        can[y:y + h, x:x + w] = over(can[y:y + h, x:x + w], im)
        cv2.rectangle(can, (x - 1, y - 1), (x + w, y + h), (90, 200, 255, 255), 1)
        cv2.putText(can, "%s %dx%d" % (k, e["w"], e["h"]), (x, y + h + 13), cv2.FONT_HERSHEY_SIMPLEX, 0.36,
                    (255, 255, 255, 255), 1, cv2.LINE_AA)
    Image.fromarray(can).save(os.path.join(TOOLS, "contact_sheet.png"))


def main():
    if "--clean" in sys.argv:
        # only the generated caches; keep tools/.cache/before/ (art-review snapshots)
        cdir = os.path.join(TOOLS, ".cache")
        for f in (os.listdir(cdir) if os.path.isdir(cdir) else []):
            p = os.path.join(cdir, f)
            if os.path.isfile(p):
                os.remove(p)
    os.makedirs(OUT, exist_ok=True)
    t0 = time.time()
    R = ref_rgb()
    NR = build_bg.remove_hero(R)
    print("bg_far", build_bg.build_far(NR))
    print("bg_mid", build_bg.build_mid(NR))
    print("bg_interior", build_bg.build_interior(R))
    print("tile_brick", build_tiles.build_brick(R))
    print("tile_brick_dark", build_tiles.build_brick_dark(R))
    print("tile_girder_v", build_tiles.build_girder(R))
    print("tile_girder_x", build_tiles.build_girder_x(R))
    print("tile_deck", build_tiles.build_deck(R))
    print("tile_stairs", build_tiles.build_stairs(R))
    print("props", build_props.build_all())
    print("hud", build_hud.build_all())
    print("hero", build_hero.build()[:4])
    entries = write_manifest()
    contact_sheet(entries)
    print("done: %d assets in %.1fs" % (len(entries), time.time() - t0))


if __name__ == "__main__":
    main()
